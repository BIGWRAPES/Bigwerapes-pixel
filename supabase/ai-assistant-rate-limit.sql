create table if not exists public.ai_generation_limits (
  user_id uuid primary key references auth.users (id) on delete cascade,
  window_started_at timestamptz not null,
  request_count integer not null check (request_count between 1 and 10)
);

create table if not exists public.ai_generation_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  requested_at timestamptz not null,
  request_count integer not null check (request_count between 1 and 10),
  is_legacy_quota_seed boolean not null default false
);

create index if not exists ai_generation_requests_user_requested_at_idx
  on public.ai_generation_requests (user_id, requested_at);

create unique index if not exists ai_generation_requests_legacy_seed_user_idx
  on public.ai_generation_requests (user_id)
  where is_legacy_quota_seed;

alter table public.ai_generation_limits enable row level security;
alter table public.ai_generation_requests enable row level security;

insert into public.ai_generation_requests (user_id, requested_at, request_count, is_legacy_quota_seed)
select limits.user_id, pg_catalog.clock_timestamp(), limits.request_count, true
from public.ai_generation_limits as limits
where limits.window_started_at > pg_catalog.clock_timestamp() - interval '1 hour'
  and not exists (
    select 1
    from public.ai_generation_requests as requests
    where requests.user_id = limits.user_id
  );

create or replace function public.consume_ai_generation_quota()
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := auth.uid();
  request_time timestamptz;
  active_requests integer;
  is_entrepreneur boolean;
begin
  if caller_id is null then
    raise exception 'Authentication is required.';
  end if;

  select exists (
    select 1
    from public.profiles
    where id = caller_id
      and account_type = 'entrepreneur'
  )
  into is_entrepreneur;

  if not is_entrepreneur then
    raise exception 'Entrepreneur access is required.';
  end if;

  insert into public.ai_generation_limits (user_id, window_started_at, request_count)
  values (caller_id, pg_catalog.clock_timestamp(), 1)
  on conflict (user_id) do nothing;

  perform 1
  from public.ai_generation_limits
  where user_id = caller_id
  for update;

  request_time := pg_catalog.clock_timestamp();

  delete from public.ai_generation_requests
  where user_id = caller_id
    and requested_at <= request_time - interval '1 hour';

  select coalesce(sum(request_count), 0)::integer
  into active_requests
  from public.ai_generation_requests
  where user_id = caller_id;

  if active_requests >= 10 then
    return false;
  end if;

  insert into public.ai_generation_requests (user_id, requested_at, request_count)
  values (caller_id, request_time, 1);

  update public.ai_generation_limits
  set window_started_at = request_time,
      request_count = active_requests + 1
  where user_id = caller_id;

  return true;
end;
$$;

revoke all on public.ai_generation_limits from public, anon, authenticated, service_role;
revoke all on public.ai_generation_requests from public, anon, authenticated, service_role;
revoke all on function public.consume_ai_generation_quota() from public, anon, service_role;
grant execute on function public.consume_ai_generation_quota() to authenticated;
